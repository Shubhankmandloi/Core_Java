package com.rays.corejava.basics;

public class Variables {

	public static void main(String[] args) {
		
//		Integer
		
		byte b = 100;
		short s = 10000;
		int i = 1000000000;
		long l = 10000000000L;
		
		System.out.println(b+" : "+s+" : "+i+" : "+l);
		
//		Float
		
		float f = 123.33f;
		double d = 12345.567;
		System.out.println(f+" : "+d);
		
//		Character
		
		char c = 'S';
		System.out.println(c);
		
//		Boolean
		boolean bo = true;
		boolean b1 = false ;
		System.out.println(bo+" : "+b1);
		
		String name = "Aditya";
		System.out.println(name);

	}

}
